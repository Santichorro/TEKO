-- TEKO V2 — updated_at lo pone la base de datos, no el navegador
-- (el reloj del cliente puede estar mal y cualquiera podría enviar otra fecha).
-- Ejecutar en Supabase → SQL Editor. Es seguro correrlo más de una vez.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $$
declare
  t text;
begin
  -- Todas las tablas del esquema public que tengan columna updated_at
  for t in
    select c.table_name
    from information_schema.columns c
    join information_schema.tables tb
      on tb.table_schema = c.table_schema and tb.table_name = c.table_name
    where c.table_schema = 'public'
      and c.column_name = 'updated_at'
      and tb.table_type = 'BASE TABLE'
  loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format(
      'create trigger set_updated_at before update on public.%I
         for each row execute function public.set_updated_at()', t);
  end loop;
end;
$$;
